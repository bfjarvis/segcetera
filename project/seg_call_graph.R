# Return a bounded neighborhood of the map. Root NULL gives the full tables.
seg_call_graph <- function(root = "seg_measure", depth = 2L,
                             direction = c("callees", "callers", "both")) {
  direction <- match.arg(direction)
  nodes <- seg_routines
  edges <- seg_calls
  stopifnot(!anyDuplicated(nodes$id), !anyDuplicated(edges),
            all(c(edges$from, edges$to) %in% nodes$id))
  if (is.null(root)) return(list(nodes = nodes, edges = edges))
  if (!is.character(root) || length(root) != 1L || !root %in% nodes$id)
    stop("Select a routine ID from seg_routines$id.", call. = FALSE)
  if (!is.numeric(depth) || length(depth) != 1L || !is.finite(depth) ||
      depth < 0 || depth != floor(depth))
    stop("'depth' must be a nonnegative integer.", call. = FALSE)

  seen <- frontier <- root
  for (level in seq_len(depth)) {
    next_nodes <- c(
      if (direction != "callers") edges$to[edges$from %in% frontier],
      if (direction != "callees") edges$from[edges$to %in% frontier]
    )
    frontier <- setdiff(next_nodes, seen)
    if (!length(frontier)) break
    seen <- c(seen, frontier)
  }
  list(nodes = nodes[nodes$id %in% seen, ],
       edges = edges[edges$from %in% seen & edges$to %in% seen, ])
}

# Optional interactive view. The tables and filtering only require tibble.
seg_plot_call_graph <- function(root = "seg_measure", depth = 2L,
                                  direction = c("callees", "callers", "both")) {
  if (!requireNamespace("visNetwork", quietly = TRUE))
    stop("Install visNetwork to open the interactive graph.", call. = FALSE)
  graph <- seg_call_graph(root, depth, direction)
  graph$nodes$label <- graph$nodes$id
  graph$nodes$group <- graph$nodes$role
  graph$nodes$title <- graph$nodes$file
  graph$edges$title <- graph$edges$kind
  graph$edges$dashes <- graph$edges$kind != "call"

  widget <- visNetwork::visNetwork(graph$nodes, graph$edges, height = "700px")
  widget <- visNetwork::visEdges(widget, arrows = "to", smooth = FALSE)
  widget <- visNetwork::visOptions(widget, nodesIdSelection = TRUE,
    highlightNearest = list(enabled = TRUE, degree = 1, hover = TRUE))
  visNetwork::visLegend(widget)
}
